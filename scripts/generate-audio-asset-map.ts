/**
 * Generates apps/game/src/audio/assetMap.generated.ts from the audio manifest.
 *
 * Metro only bundles an asset if it sees a literal `require('./path')` at
 * build time; a path built at runtime from a string is invisible to it. So
 * every clip in packages/audio/src/manifest.json gets a literal require in a
 * generated module, which ExpoClipPlayer looks up by key.
 *
 * Run from the repository root after the manifest or the clips change:
 *
 *   npm run generate:audio-map
 *
 * A test fails if the committed output has drifted from the manifest, so
 * forgetting to regenerate is caught rather than shipped.
 *
 * Needs Node 22.18+ (runs TypeScript directly).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Manifest = Record<string, string | boolean>;

/** Where the generated module lives, relative to the app root (apps/game). */
const OUTPUT_DIR_IN_APP = 'src/audio';

/** Manifest keys beginning with `_` are metadata, not clips. */
function clipEntries(manifest: Manifest): Array<[string, string]> {
  return Object.entries(manifest)
    .filter((entry): entry is [string, string] => !entry[0].startsWith('_') && typeof entry[1] === 'string')
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * The generated module's source. Pure, so a test can compare it with the
 * committed file. Manifest paths are relative to the app root; the require
 * paths are relative to the generated file, two levels down.
 */
export function renderAssetMap(manifest: Manifest): string {
  const up = OUTPUT_DIR_IN_APP.split('/').map(() => '..').join('/');
  const lines = clipEntries(manifest).map(
    ([key, path]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(`${up}/${path}`)}),`,
  );
  return [
    '// GENERATED by scripts/generate-audio-asset-map.ts. Do not edit by hand.',
    '// Regenerate with `npm run generate:audio-map` after changing the manifest or clips.',
    '//',
    '// Metro bundles an asset only if it sees a literal require() of it, so this',
    '// map exists purely to give it one per clip.',
    '',
    '/** Audio key to the bundled asset module (an opaque number under Metro). */',
    'export const AUDIO_ASSETS: Readonly<Record<string, number>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

function main(): void {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const manifest = JSON.parse(
    readFileSync(resolve(root, 'packages/audio/src/manifest.json'), 'utf8'),
  ) as Manifest;
  const out = resolve(root, 'apps/game', OUTPUT_DIR_IN_APP, 'assetMap.generated.ts');
  writeFileSync(out, renderAssetMap(manifest));
  console.log(`Wrote ${clipEntries(manifest).length} clips to ${out}`);
}

// Run only when executed directly, so a test can import renderAssetMap.
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
