/**
 * Generates packages/audio/src/manifest.json from the clip list and whatever
 * clips are actually on disk.
 *
 *   npm run generate:audio-manifest
 *
 * ## Why a generator, and why this one owns the manifest
 *
 * The voice pack arrives in pieces. The first recording session covered the
 * phonemes and the words, because those are the clips that must be a human: a
 * synthesised /t/ says "tuh", and a child blending "tuh-a-puh" never reaches
 * "tap". The letter names, interface lines and praise were left for later,
 * being the clips a synthesised voice does no harm with.
 *
 * So the pack the game plays is a mixture, and will be for as long as the
 * recording takes. This resolves each key to the best clip available for it --
 * recorded if there is one, placeholder otherwise -- which means a newly
 * recorded clip is picked up by re-running the importer and this, with nothing
 * to edit by hand and no way to point a key at a clip that is not there.
 *
 * The manifest used to be written by scripts/generate-placeholder-audio.sh, as
 * a side effect of generating the stand-in clips. That only worked while there
 * was exactly one pack; with two it would have meant two scripts writing one
 * file, each overwriting the other's half.
 *
 * Needs Node 22.18+ (runs TypeScript directly).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Packs in preference order: the first one holding a clip wins. Recorded human
 * audio always beats the stand-in.
 */
export const PACKS = ['human-au', 'placeholder-au'] as const;

/** The keys the game plays, in the order the clip list gives them. */
export function scriptKeys(script: string): string[] {
  return script
    .split('\n')
    .filter((line) => line.trim() !== '' && !line.startsWith('#'))
    .map((line) => line.split('|')[0].trim())
    .filter((key) => key !== '');
}

/**
 * The manifest, as an object.
 *
 * `has` answers whether a pack holds a clip; the caller supplies it so this
 * stays pure and a test can describe a pack layout without writing files.
 *
 * Throws if a key is in no pack at all. A key that resolves to nothing is a
 * clip the game will try to play and fail to find, and the failure would
 * surface as a child sitting in front of a screen that asked them nothing.
 */
export function buildManifest(
  keys: string[],
  has: (pack: string, key: string) => boolean,
): Record<string, unknown> {
  const out: Record<string, unknown> = {
    _comment:
      'GENERATED by scripts/generate-audio-manifest.ts. Do not edit by hand. Each key points at the best clip available for it: recorded human audio where there is some, the macOS stand-in otherwise.',
    _packs: [...PACKS],
  };
  const orphans: string[] = [];
  for (const key of keys) {
    const pack = PACKS.find((candidate) => has(candidate, key));
    if (pack === undefined) {
      orphans.push(key);
      continue;
    }
    out[key] = `assets/voice/${pack}/${key}.m4a`;
  }
  if (orphans.length > 0) {
    throw new Error(
      `No clip in any pack for: ${orphans.join(', ')}. Record them, or run scripts/generate-placeholder-audio.sh for a stand-in.`,
    );
  }
  return out;
}

function main(): void {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const keys = scriptKeys(readFileSync(resolve(root, 'packages/audio/voice-script.txt'), 'utf8'));
  const manifest = buildManifest(keys, (pack, key) =>
    existsSync(resolve(root, 'apps/game/assets/voice', pack, `${key}.m4a`)),
  );
  const out = resolve(root, 'packages/audio/src/manifest.json');
  writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`);

  const counts = new Map<string, number>();
  for (const [key, value] of Object.entries(manifest)) {
    if (key.startsWith('_') || typeof value !== 'string') continue;
    const pack = value.split('/')[2];
    counts.set(pack, (counts.get(pack) ?? 0) + 1);
  }
  const summary = [...counts].map(([pack, n]) => `${n} from ${pack}`).join(', ');
  console.log(`Wrote ${out}`);
  console.log(`${keys.length} clips: ${summary}`);
}

// Run only when executed directly, so a test can import the functions above.
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
