#!/usr/bin/env bash
#
# Generates the PLACEHOLDER voice pack. Not for use with real children —
# see docs/superpowers/specs §9.3. Requires macOS.
#
# Phonemes are spelled phonetically because `say s` produces "ess" (the letter
# name), and teaching a child that `s` says "ess" is actively harmful.
#
# Short vowels: Karen cannot be told a phoneme directly (embedded
# `[[inpt PHON]]` markup is read aloud as words on current macOS voices), and
# spelling the vowel alone gives the wrong sound: "ah" is the long vowel of
# "father" and "ih" is read as the letter name "eye". So /a/ and /i/ are cut
# from the vowel of "at" and "it": the real short vowel, minus the final t.
# Marked `vowel` in the clip list below.
#
# Run from the repository root. Compatible with macOS's stock bash 3.2.

set -euo pipefail

VOICE="${VOICE:-Karen}"   # Australian English
OUT_DIR="apps/game/assets/voice/placeholder-au"
MANIFEST="packages/audio/src/manifest.json"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

if ! command -v say >/dev/null 2>&1; then
  echo "error: 'say' not found. This script requires macOS." >&2
  exit 1
fi

if ! say -v "$VOICE" "" >/dev/null 2>&1; then
  echo "error: voice '$VOICE' is not installed." >&2
  echo "Install it in System Settings > Accessibility > Spoken Content > System Voices." >&2
  exit 1
fi

mkdir -p "$OUT_DIR"

# key|spoken text[|vowel]   (vowel: keep only the vowel of the spoken word)
CLIPS=$(cat <<'CLIPS'
ph.s|sss
ph.a|at|vowel
ph.t|tuh
ph.p|puh
ph.i|it|vowel
ph.m|mmm
ph.f|fff
ln.s|ess
ln.a|ay
ln.t|tee
ln.p|pee
ln.i|eye
ln.m|em
ln.f|ef
wd.at|at
wd.am|am
wd.if|if
wd.it|it
wd.pat|pat
wd.tap|tap
wd.pit|pit
wd.sit|sit
wd.sip|sip
wd.pip|pip
wd.fat|fat
wd.fit|fit
wd.mat|mat
wd.map|map
wd.sat|sat
wd.tip|tip
wd.sap|sap
wd.sam|Sam
wd.pam|Pam
wd.i_pronoun|I
wd.the|the
wd.a_word|a
wd.as|as
wd.is|is
ui.which_says|Which one says
ui.find_letter|Find the letter that says
ui.build_word|Build the word
ui.tap_picture|Tap the picture
ui.listen_again|Listen again
ui.lets_go|Let's go!
ui.all_done|All done!
ui.try_this_one|Try this one
praise.1|Yes!
praise.2|That's it!
praise.3|Lovely!
praise.4|You got it!
praise.5|Well done!
praise.6|Brilliant!
praise.7|Nice one!
praise.8|Perfect!
praise.9|Clever!
praise.10|Good listening!
praise.11|Beautiful!
praise.12|You're reading!
encourage.1|Nearly! Have another go.
encourage.2|Good try. Listen again.
encourage.3|Not that one. Try again.
encourage.4|Let's listen together.
CLIPS
)

# Keeps only the vowel of a short word like "at": from onset to the point where
# the energy falls away into the closure of the final consonant. stdlib only.
TRIM_VOWEL_PY='
import struct, sys, wave
src, dst = sys.argv[1], sys.argv[2]
w = wave.open(src)
rate, frames = w.getframerate(), w.getnframes()
data = list(struct.unpack("<%dh" % frames, w.readframes(frames)))
hop = int(rate * 0.01)
env = [(sum(v * v for v in data[i:i + hop]) / hop) ** 0.5 for i in range(0, frames - hop, hop)]
peak = max(env)
start = next(i for i, e in enumerate(env) if e > 0.3 * peak)
peak_at = env.index(peak)
end = next((i for i in range(peak_at, len(env)) if env[i] < 0.45 * peak), len(env))
lo, hi = max(0, start - 1) * hop, end * hop
out = data[lo:hi]
fade = int(rate * 0.015)
for i in range(fade):
    out[len(out) - 1 - i] = int(out[len(out) - 1 - i] * i / fade)
o = wave.open(dst, "wb")
o.setnchannels(1); o.setsampwidth(2); o.setframerate(rate)
o.writeframes(struct.pack("<%dh" % len(out), *out))
o.close()
'

count=0
ENTRIES="$TMP/entries.txt"
: > "$ENTRIES"

while IFS='|' read -r key text mode; do
  [ -z "$key" ] && continue
  aiff="$TMP/$key.aiff"
  m4a="$OUT_DIR/$key.m4a"
  say -v "$VOICE" -o "$aiff" "$text"
  if [ "${mode:-}" = "vowel" ]; then
    afconvert -f WAVE -d LEI16 "$aiff" "$TMP/$key.full.wav" >/dev/null
    python3 -c "$TRIM_VOWEL_PY" "$TMP/$key.full.wav" "$TMP/$key.wav"
    aiff="$TMP/$key.wav"
  fi
  rm -f "$m4a"   # afconvert refuses to overwrite
  afconvert -f m4af -d aac "$aiff" "$m4a" >/dev/null
  printf '  "%s": "assets/voice/placeholder-au/%s.m4a"\n' "$key" "$key" >> "$ENTRIES"
  count=$((count + 1))
done <<< "$CLIPS"

mkdir -p "$(dirname "$MANIFEST")"
{
  printf '{\n'
  printf '  "_comment": "GENERATED by scripts/generate-placeholder-audio.sh. PLACEHOLDER voice (macOS say, voice %s). Do not use with real children; see spec section 9.3.",\n' "$VOICE"
  printf '  "_pack": "placeholder-au",\n'
  printf '  "_placeholder": true,\n'
  # Written the long way on purpose: macOS ships bash 3.2, which has no negative
  # array indices (${arr[-1]}), so do not "modernise" this into a bash 4 idiom.
  sed '$!s/$/,/' "$ENTRIES"
  printf '}\n'
} > "$MANIFEST"

echo "Generated $count placeholder clips in $OUT_DIR"
echo "Wrote manifest to $MANIFEST"
echo
echo "REMINDER: this is a placeholder pack. The phoneme clips are approximations"
echo "and must be replaced with recorded human audio before any child testing."
