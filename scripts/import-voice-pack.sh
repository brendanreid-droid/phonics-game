#!/usr/bin/env bash
#
# Imports a recorded voice pack: trims the silence off each clip, levels it,
# encodes it for the app, and records what it measured.
#
#   ./scripts/import-voice-pack.sh [source-dir]
#
# The source defaults to the committed masters in packages/audio/masters/human-au,
# so a re-run reproduces the shipped clips exactly. Point it at a directory of
# freshly recorded WAVs to bring in new ones; copy those into the masters
# directory as well, or the next run will undo them.
#
# ## The pack may be partial, and that is the point
#
# The first recorded pack covered the phonemes and the words -- the clips that
# actually have to be a human, because a synthesised /t/ says "tuh" and a child
# who blends "tuh-a-puh" never reaches "tap". The interface lines, the praise
# and the letter names were not recorded yet, and they are the clips a
# synthesised voice can do no harm with.
#
# So this writes only the clips it finds, and scripts/generate-audio-manifest.ts
# then points each key at the recorded clip where one exists and at the
# placeholder otherwise. The game plays a mixed pack, exactly as it will while
# the rest of the recording is done, and the home screen says so.
#
# Run from the repository root. Requires macOS (afconvert) and python3.

set -euo pipefail

SOURCE_DIR="${1:-packages/audio/masters/human-au}"
OUT_DIR="apps/game/assets/voice/human-au"
MEASURED="packages/audio/src/human-au.measured.json"
SCRIPT_FILE="packages/audio/voice-script.txt"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for tool in afconvert python3; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "error: '$tool' not found." >&2
    exit 1
  fi
done

if [ ! -f "$SCRIPT_FILE" ]; then
  echo "error: $SCRIPT_FILE not found. Run from the repository root." >&2
  exit 1
fi

if [ ! -d "$SOURCE_DIR" ]; then
  echo "error: source directory $SOURCE_DIR not found." >&2
  exit 1
fi

mkdir -p "$OUT_DIR"

# Every key the game plays, from the one list that the recording script, the
# Polly generator and the macOS stand-in are all built from. A WAV in the
# source directory whose name is not a key here is a recording of something the
# game has no use for, and saying so is more useful than importing it.
KEYS=$(grep -v '^#' "$SCRIPT_FILE" | grep -v '^[[:space:]]*$' | cut -d'|' -f1)

ENTRIES="$TMP/measured.txt"
: > "$ENTRIES"
imported=0
skipped=0

for key in $KEYS; do
  src="$SOURCE_DIR/$key.wav"
  [ -f "$src" ] || { skipped=$((skipped + 1)); continue; }
  trimmed="$TMP/$key.wav"
  m4a="$OUT_DIR/$key.m4a"
  measurement=$(python3 -I scripts/lib/trim-clip.py "$src" "$trimmed")
  rm -f "$m4a"   # afconvert refuses to overwrite
  # 64 kbit mono AAC. Speech at this rate is transparent, and the pack has to
  # fit in an app a parent downloads over a phone connection.
  afconvert -f m4af -d aac -b 64000 "$trimmed" "$m4a" >/dev/null
  printf '  "%s": %s\n' "$key" "$measurement" >> "$ENTRIES"
  imported=$((imported + 1))
done

# What was in the source directory but is not a clip the game plays.
for src in "$SOURCE_DIR"/*.wav; do
  [ -f "$src" ] || continue
  name="$(basename "$src" .wav)"
  if ! echo "$KEYS" | grep -qx "$name"; then
    echo "warning: $src is not an audio key the game plays; not imported." >&2
  fi
done

{
  printf '{\n'
  printf '  "_comment": "GENERATED by scripts/import-voice-pack.sh. What the trim measured, so a test can prove it happened.",\n'
  # Written the long way because macOS ships bash 3.2; do not modernise.
  sed '$!s/$/,/' "$ENTRIES"
  printf '}\n'
} > "$MEASURED"

echo "Imported $imported clips into $OUT_DIR ($skipped keys not recorded yet)"
echo "Wrote measurements to $MEASURED"
echo
echo "Next: npm run generate:audio-manifest && npm run generate:audio-map"
